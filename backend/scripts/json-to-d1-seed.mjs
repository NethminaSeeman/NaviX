#!/usr/bin/env node
/*
 * Generates a D1 seed migration from data/production_srilanka_db.json.
 *
 * Usage (from backend/):
 *   node ./scripts/json-to-d1-seed.mjs                          # default paths
 *   node ./scripts/json-to-d1-seed.mjs <inputJson> <outputSql>
 *
 * Input  : ../data/production_srilanka_db.json (GeoJSON [lng, lat] coords)
 * Output : ./migrations/0004_seed_rich_places.sql
 */

import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";

const [, , inputArg = "../data/production_srilanka_db.json", outputArg = "./migrations/0004_seed_rich_places.sql"] =
  process.argv;

const inputPath = resolve(process.cwd(), inputArg);
const outputPath = resolve(process.cwd(), outputArg);

const raw = readFileSync(inputPath, "utf8").trim();
if (!raw) throw new Error(`Input file is empty: ${inputPath}`);

const parsed = JSON.parse(raw);
const source = Array.isArray(parsed) ? parsed : [parsed];

const rows = source.map(normalize).filter(Boolean);
if (rows.length === 0) throw new Error("No valid places found in source file.");

const lines = [
  "-- 0004_seed_rich_places.sql",
  `-- Generated by scripts/json-to-d1-seed.mjs from ${inputArg}`,
  `-- ${rows.length} locations`,
  "",
  "DELETE FROM places;",
  "",
];

for (const row of rows) {
  lines.push(
    `INSERT INTO places (location_id, name, category, era, summary, architectural_details, cultural_significance, tags_json, tts_pronunciation, tts_key_facts, lat, lng) VALUES (${[
      row.location_id,
      row.name,
      row.category,
      row.era,
      row.summary,
      row.architectural_details,
      row.cultural_significance,
      row.tags_json,
      row.tts_pronunciation,
      row.tts_key_facts,
      row.lat,
      row.lng,
    ]
      .map(toSql)
      .join(", ")});`
  );
}

lines.push("");
mkdirSync(dirname(outputPath), { recursive: true });
writeFileSync(outputPath, lines.join("\n"), "utf8");
console.log(`Generated ${rows.length} place rows -> ${outputPath}`);

// ─────────────────────────────────────────────────────────────────

function normalize(entry) {
  if (!entry || typeof entry !== "object") return null;

  const location_id = asString(entry.location_id) || asString(entry.id);
  const name = asString(entry.name);
  if (!location_id || !name) return null;

  // GeoJSON ordering is [lng, lat]; some entries also expose {coordinates:{lat,lng}}.
  const geo = entry.coordinates?.coordinates;
  let lng;
  let lat;
  if (Array.isArray(geo) && geo.length >= 2) {
    [lng, lat] = geo;
  } else {
    lat = entry.coordinates?.lat ?? entry.lat;
    lng = entry.coordinates?.lng ?? entry.lng ?? entry.lon;
  }
  lat = Number(lat);
  lng = Number(lng);
  if (!Number.isFinite(lat) || !Number.isFinite(lng)) return null;

  const deep = entry.deep_history || {};
  const tts = entry.tts_hints || {};

  return {
    location_id,
    name,
    category: asString(entry.category) || null,
    era: asString(entry.era) || null,
    summary: asString(deep.summary) || null,
    architectural_details: asString(deep.architectural_details) || null,
    cultural_significance: asString(deep.cultural_significance) || null,
    tags_json: JSON.stringify(Array.isArray(entry.tags) ? entry.tags : []),
    tts_pronunciation: asString(tts.pronunciation_guide) || null,
    tts_key_facts: asString(tts.key_facts_short) || null,
    lat,
    lng,
  };
}

function asString(value) {
  return typeof value === "string" ? value.trim() : "";
}

function toSql(value) {
  if (value === null || value === undefined) return "NULL";
  if (typeof value === "number") return Number.isFinite(value) ? String(value) : "NULL";
  return `'${String(value).replace(/'/g, "''")}'`;
}
