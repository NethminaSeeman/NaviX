#!/usr/bin/env node
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";

const [, , inputArg = "../data/mongodb/places.sample.json", outputArg = "./migrations/0002_seed_places.sql"] =
  process.argv;

const inputPath = resolve(process.cwd(), inputArg);
const outputPath = resolve(process.cwd(), outputArg);

const raw = readFileSync(inputPath, "utf8").trim();
if (!raw) {
  throw new Error(`Input file is empty: ${inputPath}`);
}

const records = parseInput(raw).map(normalizePlace).filter(Boolean);
if (records.length === 0) {
  throw new Error("No valid places found in source file.");
}

const sqlLines = [
  "-- Generated by backend/scripts/mongo-to-d1-seed.mjs",
  "-- Source: " + inputArg,
  "",
  "DELETE FROM places;",
];

for (const place of records) {
  sqlLines.push(
    `INSERT INTO places (name, nearest_site, district, verified_history, cultural_rules, lat, lng) VALUES (${[
      place.name,
      place.nearest_site,
      place.district,
      place.verified_history,
      JSON.stringify(place.cultural_rules),
      place.lat,
      place.lng,
    ]
      .map(toSqlValue)
      .join(", ")});`
  );
}

sqlLines.push("");

mkdirSync(dirname(outputPath), { recursive: true });
writeFileSync(outputPath, sqlLines.join("\n"), "utf8");
console.log(`Generated ${records.length} place rows -> ${outputPath}`);

function parseInput(text) {
  try {
    const parsed = JSON.parse(text);
    return Array.isArray(parsed) ? parsed : [parsed];
  } catch {
    return text
      .split(/\r?\n/)
      .map((line) => line.trim())
      .filter(Boolean)
      .map((line) => JSON.parse(line));
  }
}

function normalizePlace(source) {
  const name = asString(source?.name) || asString(source?.nearest_site) || "Unknown place";
  const nearest_site = asString(source?.nearest_site) || name;
  const district = asString(source?.district) || "Unknown";
  const verified_history =
    asString(source?.verified_history) || asString(source?.history) || "";

  const rules = source?.cultural_rules;
  const cultural_rules = Array.isArray(rules)
    ? rules.filter((item) => typeof item === "string")
    : typeof rules === "string"
      ? [rules]
      : [];

  const locationCoords = source?.location?.coordinates;
  const lat = toNumber(source?.coordinates?.lat ?? source?.lat ?? locationCoords?.[1]);
  const lng = toNumber(source?.coordinates?.lng ?? source?.lng ?? locationCoords?.[0]);
  if (!Number.isFinite(lat) || !Number.isFinite(lng)) return null;

  return { name, nearest_site, district, verified_history, cultural_rules, lat, lng };
}

function asString(value) {
  return typeof value === "string" ? value.trim() : "";
}

function toNumber(value) {
  if (value && typeof value === "object") {
    if ("$numberDouble" in value) return Number(value.$numberDouble);
    if ("$numberInt" in value) return Number(value.$numberInt);
    if ("$numberLong" in value) return Number(value.$numberLong);
  }
  return Number(value);
}

function toSqlValue(value) {
  if (value === null || value === undefined) return "NULL";
  if (typeof value === "number") return Number.isFinite(value) ? String(value) : "NULL";
  return `'${String(value).replace(/'/g, "''")}'`;
}
